#!/usr/bin/env python3
"""Generate default_dialect.goose: the default ASCII dialect.

The table comes from the default_ascii dict of the Python package iso8583
(pyiso8583), file iso8583/specs.py. The script reads the dict as data with
ast.literal_eval. It never runs the file.

Fields 1 and 65 belong to the package, so the table skips them. The mask
modes are the package rule: PAN for 2, 34, 102 and 103, full for 35, 36,
45, 52, 53 and 55.

Run:
  python3 test/make_default.py path/to/iso8583/specs.py > default_dialect.goose
"""
import ast
import sys

PAN = {2, 34, 102, 103}
FULL = {35, 36, 45, 52, 53, 55}
# Width of the ASCII length prefix to the kind constant of the package.
KIND = {0: 0, 2: 1, 3: 2}


def load(path):
    tree = ast.parse(open(path, encoding="utf-8").read())
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
                isinstance(t, ast.Name) and t.id == "default_ascii" for t in node.targets):
            return ast.literal_eval(node.value)
    sys.exit("default_ascii not found")


def main(path):
    spec = load(path)
    rows = []
    for i in range(2, 129):
        if i == 65:
            continue
        f = spec[str(i)]
        if f["data_enc"] != "ascii" or f["len_enc"] != "ascii" or f.get("len_count", "bytes") != "bytes":
            sys.exit("field %d is not plain ASCII" % i)
        mask = 1 if i in PAN else 2 if i in FULL else 0
        rows.append((i, KIND[f["len_type"]], f["max_len"], mask))
    if len(rows) != 126:
        sys.exit("expected 126 fields")
    print("// Generated by test/make_default.py. Do not edit by hand.")
    print("namespace iso8583;")
    print("")
    print("import std;")
    print("")
    print("// One row per field: id, kind (0 fixed, 1 LLVAR, 2 LLLVAR), max_len, mask mode.")
    print("const DEFAULT_ASCII_ROWS: i64[%d] = [" % (len(rows) * 4))
    for r in rows:
        print("    %d, %d, %d, %d," % r)
    print("];")
    print("")
    print("// Fills d with the default ASCII dialect: a four-digit ASCII MTI, hex")
    print("// bitmaps of 16 characters, and the fields 2 to 128 as ISO 8583:1987")
    print("// lists them. Field 65 is the tertiary indicator and is not a field.")
    print("fn dialect_default_ascii(d: Dialect&) {")
    print("    dialect_init(d, ENC_ASCII, BITMAP_HEX_ASCII, 2);")
    print("    for r in 0..%d {" % len(rows))
    print("        let b = r * 4;")
    print("        dialect_field(d, DEFAULT_ASCII_ROWS[b], DEFAULT_ASCII_ROWS[b + 1], ENC_ASCII, ENC_ASCII,")
    print("                      UNIT_BYTES, DEFAULT_ASCII_ROWS[b + 2], PAD_LEFT, DEFAULT_ASCII_ROWS[b + 3]);")
    print("    }")
    print("}")


if len(sys.argv) != 2:
    sys.exit(__doc__)
main(sys.argv[1])
