#!/usr/bin/env python3
"""Generate ebcdic.goose: the code page 500 tables for the 128 ASCII characters.

The tables come from the Python cp500 codec. A byte of the EBCDIC side that
has no ASCII character maps to 0. The package tells that case apart from a
real NUL by testing the EBCDIC byte.

Run:
  python3 test/make_ebcdic.py > ebcdic.goose
"""

def main():
    to_ascii = {}
    to_ebcdic = {}
    for b in range(256):
        c = bytes([b]).decode("cp500")
        if len(c) == 1 and ord(c) < 128 and ord(c) not in to_ebcdic:
            to_ascii[b] = ord(c)
            to_ebcdic[ord(c)] = b
    if len(to_ebcdic) != 128 or any(to_ebcdic[to_ascii[b]] != b for b in to_ascii):
        raise SystemExit("cp500 does not map the 128 ASCII characters one to one")

    def table(name, d):
        print("const %s: u8[256] = [" % name)
        for i in range(0, 256, 16):
            print("    " + ", ".join("0x%02x" % d.get(i + j, 0) for j in range(16)) + ",")
        print("];")

    print("// Generated by test/make_ebcdic.py. Do not edit by hand.")
    print("namespace iso8583;")
    print("")
    print("// Code page 500 byte to ASCII character. 0 when the byte has none.")
    table("EBCDIC_TO_ASCII", to_ascii)
    print("")
    print("// ASCII character to code page 500 byte. Only the first 128 entries are used.")
    table("ASCII_TO_EBCDIC", to_ebcdic)

main()
