#!/usr/bin/env python3
"""Generate ebcdic.goose: the EBCDIC code page tables of the package.

Pages 500 and 037 come from the Python codecs cp500 and cp037. Python has
no cp1047 codec, so page 1047 comes from `iconv -f ASCII -t IBM1047`. The
script cross-checks every page and fails on a difference:

- `iconv -t IBM037` and `iconv -t IBM500` against the Python codecs.
- The printable ASCII entries of the moov-io 1047 test map
  (encoding/ebcdic1047_test.go, read as text, never run) against iconv.

The tables hold 768 entries each, indexed page * 256 + byte. A byte of
the EBCDIC side that has no ASCII character maps to 0. The package tells
that case apart from a real NUL by testing the EBCDIC byte.

The script also writes test/suite/page_cases.goose with the iconv byte of
each of the 128 ASCII characters on each page, as an independent oracle
for the tests.

Run:
  python3 test/make_ebcdic.py path/to/moov-io/iso8583
"""
import subprocess
import sys

PAGES = [("500", "cp500", "IBM500"), ("037", "cp037", "IBM037"), ("1047", None, "IBM1047")]


def iconv(text, target):
    p = subprocess.run(["iconv", "-f", "ASCII", "-t", target],
                       input=text.encode("ascii"), capture_output=True)
    if p.returncode != 0:
        sys.exit("iconv failed for %s: %s" % (target, p.stderr.decode()))
    return p.stdout


def iconv_char(ch, target):
    out = iconv(ch, target)
    if len(out) != 1:
        sys.exit("iconv %s maps %r to %d bytes" % (target, ch, len(out)))
    return out[0]


def python_page(codec):
    to_ascii = {}
    to_ebcdic = {}
    for b in range(256):
        c = bytes([b]).decode(codec)
        if len(c) == 1 and ord(c) < 128 and ord(c) not in to_ebcdic:
            to_ascii[b] = ord(c)
            to_ebcdic[ord(c)] = b
    if len(to_ebcdic) != 128 or any(to_ebcdic[to_ascii[b]] != b for b in to_ascii):
        sys.exit("%s does not map the 128 ASCII characters one to one" % codec)
    return to_ascii, to_ebcdic


def iconv_page(target):
    to_ascii = {}
    to_ebcdic = {}
    for code in range(128):
        b = iconv_char(chr(code), target)
        if b in to_ascii and to_ascii[b] != code:
            sys.exit("iconv %s maps two ASCII characters to 0x%02x" % (target, b))
        to_ascii[b] = code
        to_ebcdic[code] = b
    return to_ascii, to_ebcdic


def moov_1047_map(path):
    """Reads the printable ASCII entries of the moov-io 1047 test map."""
    import re
    pat = re.compile(r'^\s*"((?:[^"\\]|\\.)*)":\s*0x([0-9A-Fa-f]{2}),\s*$')
    out = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            m = pat.match(line)
            if not m:
                continue
            key = m.group(1).replace('\\"', '"').replace("\\\\", "\\")
            if len(key) == 1 and 0x20 <= ord(key) <= 0x7E:
                out[ord(key)] = int(m.group(2), 16)
    return out


def main(moov_root):
    pages = {}
    for name, codec, target in PAGES:
        if codec is not None:
            a, e = python_page(codec)
            ia, ie = iconv_page(target)
            if a != ia or e != ie:
                sys.exit("iconv %s disagrees with the Python codec %s" % (target, codec))
            pages[name] = (a, e, ie)
        else:
            a, e = iconv_page(target)
            pages[name] = (a, e, e)
    test_map = moov_1047_map(moov_root + "/encoding/ebcdic1047_test.go")
    if not test_map:
        sys.exit("no printable entries found in ebcdic1047_test.go")
    for code, b in sorted(test_map.items()):
        if pages["1047"][2][code] != b:
            sys.exit("1047 mismatch at U+%04X: iconv 0x%02x, test map 0x%02x"
                     % (code, pages["1047"][2][code], b))

    def table(out, name, d):
        out.append("const %s: u8[768] = [" % name)
        for page in range(3):
            for i in range(0, 256, 16):
                row = ", ".join("0x%02x" % d.get(page * 256 + i + j, 0) for j in range(16))
                out.append("    " + row + ",")
        out.append("];")

    pages_list = [pages[PAGES[p][0]] for p in range(3)]
    lines = []
    lines.append("// Generated by test/make_ebcdic.py. Do not edit by hand.")
    lines.append("namespace iso8583;")
    lines.append("")
    lines.append("// EBCDIC byte to ASCII character, per code page. Index is page * 256")
    lines.append("// plus the EBCDIC byte. 0 when the byte has no ASCII character.")
    table(lines, "EBCDIC_TO_ASCII",
          {p * 256 + b: c for p, (a, _, _) in enumerate(pages_list) for b, c in a.items()})
    lines.append("")
    lines.append("// ASCII character to EBCDIC byte, per code page. Index is page * 256")
    lines.append("// plus the ASCII code. Only the first 128 entries of each page are used.")
    table(lines, "ASCII_TO_EBCDIC",
          {p * 256 + c: b for p, (_, e, _) in enumerate(pages_list) for c, b in e.items()})
    with open("ebcdic.goose", "w") as f:
        f.write("\n".join(lines) + "\n")

    cases = ["// Generated by test/make_ebcdic.py. Do not edit by hand.",
             "namespace suite;", "",
             "// The EBCDIC byte of each of the 128 ASCII characters on each",
             "// code page, read from iconv as an independent oracle.",
             "const PAGE_CASES: u8[384] = ["]
    for p in range(3):
        for code in range(0, 128, 16):
            row = ", ".join("0x%02x" % pages[PAGES[p][0]][2][code + j] for j in range(16))
            cases.append("    " + row + ",")
    cases.append("];")
    with open("test/suite/page_cases.goose", "w") as f:
        f.write("\n".join(cases) + "\n")
    print("ebcdic.goose and test/suite/page_cases.goose written")


if len(sys.argv) != 2:
    sys.exit(__doc__)
main(sys.argv[1])
