#!/usr/bin/env python3
"""Generate test/suite/tlv_cases.goose: BER-TLV samples for the tests.

Sources, read as text and never run:
- the tag vectors of encoding/bertlv_test.go in the moov-io iso8583 clone;
- the ICC hex string of exp/emv/emv_test.go in the same clone.

The script also builds more containers with its own BER encoder: tags of
one, two and three bytes, and lengths of 0, 1, 127, 128, 255, 256 and
larger. The encoder and the parser here are independent of the package.

Each case gives the payload as hex and the entries as `TAG:VALUE` pairs in
hex, joined by commas, in wire order.

Run:
  python3 test/make_tlv_cases.py path/to/moov-io/iso8583 > test/suite/tlv_cases.goose
"""
import random
import re
import sys


def enc_len(n):
    if n < 128:
        return bytes([n])
    if n < 256:
        return bytes([0x81, n])
    return bytes([0x82, n >> 8, n & 255])


def parse_tag(buf, pos):
    n = 1
    if buf[pos] & 0x1F == 0x1F:
        while True:
            b = buf[pos + n]
            n += 1
            if b & 0x80 == 0:
                break
    return buf[pos:pos + n], pos + n


def parse_len(buf, pos):
    b = buf[pos]
    if b < 128:
        return b, pos + 1
    k = b & 0x7F
    return int.from_bytes(buf[pos + 1:pos + 1 + k], "big"), pos + 1 + k


def parse(buf):
    out = []
    pos = 0
    while pos < len(buf):
        tag, pos = parse_tag(buf, pos)
        n, pos = parse_len(buf, pos)
        out.append((tag, buf[pos:pos + n]))
        pos += n
    if pos != len(buf):
        sys.exit("sample does not parse to its end")
    return out


def build(entries):
    out = b""
    for tag, val in entries:
        out += tag + enc_len(len(val)) + val
    return out


def moov_tags(path):
    pat = re.compile(r'\[\]byte\{([^}]*)\},\s*\[\]byte\("([0-9A-F]+)"\)')
    tags = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            m = pat.search(line)
            if m:
                raw = bytes(int(x.strip(), 16) for x in m.group(1).split(","))
                if raw.hex().upper() != m.group(2):
                    sys.exit("moov vector disagrees with itself: " + line)
                tags.append(raw)
    return tags


def moov_icc(path):
    with open(path, encoding="utf-8") as f:
        m = re.search(r"iccData := `([0-9a-fA-F]+)`", f.read())
    if not m:
        sys.exit("no ICC sample found")
    return bytes.fromhex(m.group(1))


def main(root):
    tags = moov_tags(root + "/encoding/bertlv_test.go")
    if len(tags) < 7:
        sys.exit("expected at least 7 tag vectors, found %d" % len(tags))
    rng = random.Random(8583)
    cases = []
    # An empty container.
    cases.append([])
    # One entry per moov tag vector, with growing value lengths.
    lens = [0, 1, 5, 127, 128, 255, 256]
    for i, t in enumerate(tags):
        cases.append([(t, bytes(rng.randrange(256) for _ in range(lens[i % len(lens)])))])
    # A mix of the moov tags in one container.
    cases.append([(t, bytes(rng.randrange(256) for _ in range(4 + i))) for i, t in enumerate(tags)])
    # Long lengths that stay below 999 bytes in all.
    cases.append([(bytes([0x9F, 0x26]), bytes(rng.randrange(256) for _ in range(300))),
                  (bytes([0x95]), bytes(5)),
                  (bytes([0x5F, 0x2A]), bytes([0x08, 0x40]))])
    cases.append([(bytes([0xDF, 0xA8, 0x01]), bytes(rng.randrange(256) for _ in range(600)))])
    # The ICC sample of moov-io.
    icc = moov_icc(root + "/exp/emv/emv_test.go")
    entries = parse(icc)
    seen = set()
    for t, _ in entries:
        if t in seen:
            sys.exit("the ICC sample repeats a tag: " + t.hex())
        seen.add(t)
    if build(entries) != icc:
        sys.exit("the ICC sample is not in its shortest form")
    if len(icc) > 999:
        sys.exit("the ICC sample does not fit a field")
    cases.append(entries)

    print("// Generated by test/make_tlv_cases.py. Do not edit by hand.")
    print("namespace suite;")
    print("")
    print("fn tlv_count() -> i64 { return %d; }" % len(cases))
    print("")
    print("// The payload of case i as hex.")
    print("fn tlv_payload(i: i64) -> const u8[:] {")
    for i, c in enumerate(cases):
        print('    if i == %d { return "%s"; }' % (i, build(c).hex().upper()))
    print('    return "";')
    print("}")
    print("")
    print("// The entries of case i as TAG:VALUE hex pairs, joined by commas.")
    print("fn tlv_entries(i: i64) -> const u8[:] {")
    for i, c in enumerate(cases):
        row = ",".join("%s:%s" % (t.hex().upper(), v.hex().upper()) for t, v in c)
        print('    if i == %d { return "%s"; }' % (i, row))
    print('    return "";')
    print("}")


if len(sys.argv) != 2:
    sys.exit(__doc__)
main(sys.argv[1])
